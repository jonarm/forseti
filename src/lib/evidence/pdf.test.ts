import { describe, expect, it } from "vitest";

import { extractText } from "./extract";
import { groupItemsIntoLines, MAX_PDF_PAGES, type PdfTextItem } from "./pdf";

/**
 * Local PDF extraction.
 *
 * Two halves, deliberately separate. `groupItemsIntoLines` is pure, so the
 * layout rules — what counts as a new row, what counts as a column — are pinned
 * directly against synthetic fragments; constructing a PDF that produces a
 * specific column gap is far harder than writing the three items down.
 *
 * The rest goes through real PDFs, because the things worth checking there are
 * the ones a hand-written fixture cannot fake: that pdf.js is wired up at all,
 * that the page cap holds, and that a file with no text layer reports failure
 * rather than an empty success — the assertion the Files API fallback in
 * `index.ts` depends on.
 */

// ---------------------------------------------------------------------------
// A PDF, byte by byte
// ---------------------------------------------------------------------------

/** One text fragment placed at an absolute position on the page. */
function drawText(x: number, y: number, text: string, size = 10): string {
  return `BT /F1 ${size} Tf ${x} ${y} Td (${text}) Tj ET`;
}

/**
 * Build a minimal but valid PDF from per-page content streams.
 *
 * Hand-assembled rather than generated by a library, for the same reason
 * `hardening.test.ts` writes its own ZIPs: a fixture we control byte for byte is
 * the only way to test the boundaries (an empty page, two hundred of them)
 * without shipping binaries into the repo.
 */
function makePdf(pageContents: string[]): Buffer {
  const objects: string[] = [];

  // 1 catalog, 2 page tree, 3 font, then two objects per page.
  const pageIds = pageContents.map((_, i) => 4 + i * 2);

  objects.push("<< /Type /Catalog /Pages 2 0 R >>");
  objects.push(
    `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pageContents.length} >>`,
  );
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

  pageContents.forEach((content, i) => {
    const contentId = 5 + i * 2;
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents ${contentId} 0 R /Resources << /Font << /F1 3 0 R >> >> >>`,
    );
    objects.push(
      `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    );
  });

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];

  objects.forEach((body, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;

  return Buffer.from(pdf, "latin1");
}

// ---------------------------------------------------------------------------
// Layout reconstruction
// ---------------------------------------------------------------------------

/** pdf.js reports position in a 6-element matrix; only [4] and [5] are read. */
function item(x: number, y: number, str: string, width = 20): PdfTextItem {
  return { str, transform: [1, 0, 0, 1, x, y], width };
}

describe("groupItemsIntoLines", () => {
  it("groups fragments sharing a baseline into one line", () => {
    expect(
      groupItemsIntoLines([item(72, 700, "Data"), item(100, 700, "category")]),
    ).toEqual(["Data category"]);
  });

  it("reads top to bottom, since PDF y grows upwards", () => {
    // Deliberately supplied bottom-first: the sort is what has to fix it.
    expect(
      groupItemsIntoLines([item(72, 600, "second"), item(72, 700, "first")]),
    ).toEqual(["first", "second"]);
  });

  it("tolerates small baseline drift within a line", () => {
    // Kerning and font-size changes move the baseline a point or two without
    // starting a new row.
    expect(
      groupItemsIntoLines([item(72, 700, "same"), item(100, 701.5, "row")]),
    ).toEqual(["same row"]);
  });

  it("splits a line when the baseline moves further than the tolerance", () => {
    expect(
      groupItemsIntoLines([item(72, 700, "one"), item(72, 690, "two")]),
    ).toEqual(["one", "two"]);
  });

  it("turns a wide gap between fragments into a tab", () => {
    // "Category" ends at 92; "24 months" starts at 300. That is a column.
    expect(
      groupItemsIntoLines([
        item(72, 700, "Category", 20),
        item(300, 700, "24 months", 40),
      ]),
    ).toEqual(["Category\t24 months"]);
  });

  it("reads a wide whitespace fragment as a column, not a space", () => {
    // The case that matters most: pdf.js synthesises an item to span the gap
    // rather than leaving one, so the width of that item is the only signal.
    // Miss this and every table in every PDF flattens into prose.
    expect(
      groupItemsIntoLines([
        item(72, 700, "Behavioural events", 85),
        item(157, 700, " ", 103),
        item(260, 700, "24 months", 47),
      ]),
    ).toEqual(["Behavioural events\t24 months"]);
  });

  it("reads a narrow whitespace fragment as an ordinary space", () => {
    expect(
      groupItemsIntoLines([
        item(72, 700, "two", 20),
        item(92, 700, " ", 3),
        item(95, 700, "words", 30),
      ]),
    ).toEqual(["two words"]);
  });

  it("drops empty fragments and rows that hold nothing but whitespace", () => {
    expect(
      groupItemsIntoLines([
        item(72, 700, "", 0),
        item(72, 690, "   ", 30),
        item(72, 680, "real", 20),
      ]),
    ).toEqual(["real"]);
  });

  it("returns nothing for no items", () => {
    expect(groupItemsIntoLines([])).toEqual([]);
  });
});

