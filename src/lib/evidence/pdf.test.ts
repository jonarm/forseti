// End to end, through extractText
// ---------------------------------------------------------------------------

describe("extractText, pdf", () => {
  it("extracts text from a real PDF", async () => {
    const pdf = makePdf([drawText(72, 720, "Information Security Policy", 12)]);

    const result = await extractText(pdf, "pdf", "policy.pdf");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain("Information Security Policy");
    expect(result.truncated).toBe(false);
  });

  it("keeps a table a table", async () => {
    // The justification for the whole change: sending PDFs natively preserved
    // layout, and this is the assertion that extraction did not throw it away.
    const pdf = makePdf([
      [
        drawText(72, 720, "Retention Schedule", 12),
        drawText(72, 690, "Data category"),
        drawText(260, 690, "Retention period"),
        drawText(72, 670, "Behavioural events"),
        drawText(260, 670, "24 months"),
      ].join("\n"),
    ]);

    const result = await extractText(pdf, "pdf", "retention.pdf");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain("Data category\tRetention period");
    expect(result.text).toContain("Behavioural events\t24 months");
  });

  it("reports failure for a PDF with no text layer", async () => {
    // A scan looks like this: real pages, no text. `processUpload` reads this
    // exact failure and falls back to the Files API, so it must not come back
    // as an empty success.
    const result = await extractText(makePdf(["", ""]), "pdf", "scan.pdf");

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.reason).toMatch(/no readable text/i);
  });

  it("stops at the page cap and says it truncated", async () => {
    const pages = Array.from({ length: MAX_PDF_PAGES + 5 }, (_, i) =>
      drawText(72, 720, `Page ${i + 1} of many`),
    );

    const result = await extractText(makePdf(pages), "pdf", "long.pdf");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.truncated).toBe(true);
    expect(result.text).toContain("Page 1 of many");
    expect(result.text).not.toContain(`Page ${MAX_PDF_PAGES + 1} of many`);
  }, 60_000);

  it("answers a corrupt PDF with a reason rather than a throw", async () => {
    // Hostile input is expected here, so the route can return 400. A throw
    // escaping this call would be a 500, which is the attacker winning.
    const corrupt = Buffer.concat([
      Buffer.from("%PDF-1.4\n", "ascii"),
      Buffer.from([0x00, 0xff, 0xfe, 0x42, 0x00, 0x13, 0x37]),
    ]);

    const result = await extractText(corrupt, "pdf", "broken.pdf");

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.reason.length).toBeGreaterThan(0);
  });
});

// ---------------------------------------------------------------------------
// CSV, which shares the text path
// ---------------------------------------------------------------------------

describe("extractText, csv", () => {
  const csv = "Data category,Retention period\nBehavioural events,24 months";

  it("aligns a CSV into the same tab-separated rows as a spreadsheet", async () => {
    const result = await extractText(Buffer.from(csv), "text", "retention.csv");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain("Data category\tRetention period");
  });

  it("leaves a plain text file alone", async () => {
    // Same bytes, different name. The extension picks a formatter and nothing
    // else, so a .txt keeps its commas.
    const result = await extractText(Buffer.from(csv), "text", "notes.txt");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain("Data category,Retention period");
  });

  it("falls back to raw text when a .csv is not tabular", async () => {
    const prose = "We retain behavioural events for 24 months.";

    const result = await extractText(Buffer.from(prose), "text", "policy.csv");

    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toBe(prose);
  });
});
